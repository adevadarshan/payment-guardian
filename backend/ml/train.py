# backend/ml/train.py — synthetic-data model training (Slice 4, offline dev-only).
# NEVER runs inside the API process. Generates data we own, trains a small
# logistic regression, evaluates on a HELD-OUT split, writes artifacts.
#
# HONESTY CONTRACT (see EVAL.md): labels come from the deterministic scorer,
# so the model learns to approximate our own rules on synthetic variations.
# It adds no independent fraud knowledge. Golden corpora are regression/smoke
# tests, NOT the performance evaluation set. Never claim otherwise.
#
# Usage:  python backend/ml/train.py --out backend/app/ml/artifacts
import argparse
import hashlib
import json
import random
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

SEED = 7
VERSION = "synthetic-v1"

AMOUNTS = [50, 150, 300, 800, 1500, 2500, 3500, 5000, 9500, 12000,
           25000, 60000, 120000, 199000]
CATEGORIES = ["Groceries", "Utilities", "Travel", "Electronics", "Crypto",
              "Gambling", "Peer Transfer", "Entertainment", "Healthcare", "Other"]
HOURS = [2, 3, 9, 14, 19, 23]
NOTES = [None, "groceries", "urgent verify kyc", "refund claim", "thanks",
         "OTP shared here", "lottery prize claim"]
PAYEES = ["Corner Shop", "Unknown", "Vendor"]
BALANCE_RATIOS = [0.2, 0.5, 1.5, 3.0, 10.0]


def generate(seed: int = SEED):
    """Yield (payment_kwargs, hour) synthetic cases. Deterministic given seed."""
    rng = random.Random(seed)
    cases = []
    for amount in AMOUNTS:
        for category in CATEGORIES:
            for hour in HOURS:
                note = rng.choice(NOTES)
                payee = rng.choice(PAYEES)
                ratio = rng.choice(BALANCE_RATIOS)
                balance = max(amount * 1.01, amount / max(ratio, 0.01))
                cases.append(({
                    "amount": float(amount), "currency": "INR",
                    "payee_id": "synth@bank", "payee_name": payee,
                    "sender_balance": round(balance, 2), "note": note,
                    "channel": "upi", "merchant_category": category,
                }, hour))
    rng.shuffle(cases)
    return cases


def build_dataset(seed: int = SEED):
    """Build (X, y) with labels from the deterministic scorer's bands."""
    from app.ml.features import build as build_features
    from app.pipeline import run as pipeline
    from app.schemas.analyze import PaymentInput

    cases = generate(seed)
    rows = []
    for kwargs, hour in cases:
        payment = PaymentInput(**kwargs)
        verdict = pipeline.analyze_request(
            analysis_type="payment", payment=payment, hour=hour)
        label = 0 if verdict["risk_level"] == "SAFE" else 1
        rows.append((build_features(payment, hour=hour), label))
    return rows


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, help="artifacts directory")
    parser.add_argument("--seed", type=int, default=SEED)
    args = parser.parse_args()

    from sklearn.linear_model import LogisticRegression
    from sklearn.metrics import accuracy_score, roc_auc_score
    from sklearn.model_selection import train_test_split
    import joblib

    from app.ml.features import N_FEATURES, SCHEMA_VERSION

    rows = build_dataset(args.seed)
    X = [r[0] for r in rows]
    y = [r[1] for r in rows]
    assert all(len(v) == N_FEATURES for v in X)
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, random_state=args.seed, stratify=y)
    model = LogisticRegression(max_iter=2000, random_state=args.seed)
    model.fit(X_train, y_train)
    proba = model.predict_proba(X_test)[:, 1]
    pred = (proba >= 0.5).astype(int).tolist()
    metrics = {
        "n_total": len(rows),
        "n_train": len(X_train),
        "n_test": len(X_test),
        "accuracy": round(float(accuracy_score(y_test, pred)), 4),
        "auc": round(float(roc_auc_score(y_test, proba)), 4),
    }

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    model_path = out / "model.joblib"
    joblib.dump(model, model_path)
    digest = hashlib.sha256(model_path.read_bytes()).hexdigest()
    metadata = {
        "version": VERSION,
        "feature_schema": SCHEMA_VERSION,
        "n_features": N_FEATURES,
        "sha256": digest,
        "seed": args.seed,
        "trained_at": datetime.now(timezone.utc).isoformat(),
        "eval": metrics,
        "provenance": ("synthetic data generated by backend/ml/train.py from "
                       "programmatic grids; labels from the deterministic scorer"),
    }
    (out / "metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(json.dumps(metrics, indent=2))
    print(f"wrote {model_path} sha256={digest[:12]}...")


if __name__ == "__main__":
    main()
